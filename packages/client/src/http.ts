/**
 * The transport: the one place in the CLI and the MCP server where an HTTP request is made.
 *
 * Everything here is a rule whose divergence between the two adapters would be a defect, which
 * is why it is a `fetch` wrapper installed under the generated client rather than middleware each
 * adapter registers. Four of them:
 *
 *   1. **The credential is attached here and nowhere else**, so no adapter can compose a request
 *      that reaches TCMS without one, and no adapter can send one anywhere else — see
 *      {@link resolveBaseUrl}.
 *   2. **Every request carries a deadline.** See `budgets.ts`.
 *   3. **A refusal becomes a `TcmsApiError` with its problem document read**, once. The generated
 *      client's own `error` branch is therefore unreachable at runtime, which is what lets the
 *      command core be written in terms of values and exceptions rather than result tuples.
 *   4. **A timeout is kept apart from a cancellation.** A cancelled call is not a failure and must
 *      never be reported as one; a timed-out write is a failure whose result is *unknown*, which
 *      is a different sentence to say to a user and a different thing for an agent to do next.
 */
import { TIMEOUTS, type TimeoutClass } from './budgets.js';
import { TcmsApiError, TcmsClientError, TcmsTimeoutError } from './errors.js';

/** The contract's `servers:` entry. Composed here, so no caller holds a copy of the routing. */
export const API_PREFIX = '/api/v1';

/**
 * A bearer credential, or a function returning one.
 *
 * The function form exists because a long-lived MCP session outlives any single read of a
 * credential file: a token rotated on disk should take effect on the next request rather than on
 * the next restart. It is called per request, so it must be cheap.
 */
export type TokenSource = string | (() => string);

export interface TransportOptions {
  /**
   * The TCMS instance's origin — `https://tcms.example.com`. **Not** the `/api/v1` prefix; that
   * belongs to the contract and is added here.
   */
  baseUrl: string;
  token: TokenSource;
  /** Overrides the global `fetch`. The seam the tests drive, and the one a proxy would use. */
  fetch?: typeof globalThis.fetch;
  /** Default budget class for requests that do not name one. */
  timeoutClass?: TimeoutClass;
  /**
   * Sent verbatim as `User-Agent`. This is what `audit_event` records to tell a CLI edit from an
   * MCP one — the surface spec §4.7: there is no `via` column and this plus `actor_token_id` is
   * what carries the same fact.
   */
  userAgent: string;
}

/**
 * Per-request knobs the generated client does not model.
 *
 * They ride on `init` as a single property rather than as loose keys because openapi-fetch
 * forwards unknown `init` members to `fetch`, where a stray `idempotencyKey` would be silently
 * ignored — a header that does not arrive, on exactly the requests that most need it.
 */
export interface TcmsRequestOptions {
  signal?: AbortSignal;
  timeoutClass?: TimeoutClass;
  /**
   * An explicit deadline in milliseconds, overriding the class.
   *
   * The class is the right default because it encodes *why* a budget is what it is; this exists
   * because the person running the CLI knows things the class cannot — a slow VPN, a report over
   * a year of runs — and `--timeout` is the honest answer to that rather than raising the class
   * for everybody. It is also what lets the timeout behaviour be tested in milliseconds instead
   * of waiting out a real budget.
   */
  timeoutMs?: number;
  /**
   * One key per **user intent**, reused across every retry of that intent. Generated by
   * `core/idempotency.ts`; passed here rather than composed here, because "is this the same
   * intent as last time" is a question only the caller can answer.
   */
  idempotencyKey?: string;
  /** `lockVersion` from the paired read, sent as `If-Match`. See `core/concurrency.ts`. */
  ifMatch?: string | number;
  /**
   * Called with the status of a **successful** answer, once, before the body reaches the caller.
   *
   * It exists because `client.ts` returns `result.data` and drops everything else, so a success
   * status was readable nowhere in this package — and on sixteen operations the contract says the
   * two success statuses mean different things: 201 created it, 200 replayed an `Idempotency-Key`
   * and *nothing was created by this request*. §204 found the CLI printing `Created` for both.
   *
   * A callback rather than a returned status, because that is the shape that survives the spread
   * every call site writes (`tcms: { ...request, ...createIntent(…) }`): a field written onto the
   * options object would be written onto the copy. `createIntent` is the only caller and
   * {@link core/mutation.CreateIntent} is the readable form of it — a bare hook here would invite
   * a second, per-call-site answer to a question the core already answers once.
   *
   * Not called on a refusal: `http.ts` has thrown by then, and a `TcmsApiError` already carries
   * its status.
   */
  observeStatus?: (status: number) => void;
}

const OPTIONS_KEY = 'tcms';

/** Attaches this package's per-request options to an openapi-fetch `init`. */
export function withOptions<T extends object>(init: T, options: TcmsRequestOptions): T {
  return { ...init, [OPTIONS_KEY]: options };
}

/**
 * Reads this package's options off an init object or off the Request openapi-fetch built.
 *
 * Both, because openapi-fetch does not pass `init` through to `fetch` at all — it copies
 * unrecognised init members onto the Request object instead. A reader that knew only one of the
 * two places would work for direct transport callers and silently drop every option that came
 * through the generated client, or the reverse.
 */
function optionsOf(source: unknown): TcmsRequestOptions {
  if (source && typeof source === 'object' && OPTIONS_KEY in source) {
    return (source as Record<string, TcmsRequestOptions>)[OPTIONS_KEY] ?? {};
  }
  return {};
}

/**
 * Validates the instance origin and composes the contract's prefix onto it.
 *
 * The check is not defensive programming. This function's output is where a bearer token is
 * sent, so a `baseUrl` that is not what the operator meant is a credential disclosed to whoever
 * owns that host. The SPA has the same guard on `fetchArtifact` for the same reason and states
 * it in those words; here the string comes from a config file or an environment variable rather
 * than from the server, which is a wider door, not a narrower one.
 */
export function resolveBaseUrl(baseUrl: string): string {
  let parsed: URL;
  try {
    parsed = new URL(baseUrl);
  } catch {
    throw new TcmsClientError(
      `'${baseUrl}' is not a URL. Give the TCMS instance's origin, like `
        + `'https://tcms.example.com' — the /api/v1 prefix is added for you.`,
    );
  }

  if (parsed.protocol !== 'https:' && parsed.protocol !== 'http:') {
    throw new TcmsClientError(
      `Refusing to send a credential over '${parsed.protocol}'. Use https, or http for a local `
        + 'instance.',
    );
  }

  if (parsed.search || parsed.hash) {
    throw new TcmsClientError(
      `'${baseUrl}' carries a query string or fragment. Give the origin alone.`,
    );
  }

  // A trailing slash on the origin would compose `//api/v1`, which some proxies route and some
  // 404 — a difference that shows up only in deployment.
  const origin = `${parsed.origin}${parsed.pathname.replace(/\/+$/, '')}`;
  return `${origin}${API_PREFIX}`;
}

/** The validated base URL and the `fetch` bound to it, which is all the client needs. */
export interface Transport {
  readonly baseUrl: string;
  readonly fetch: typeof globalThis.fetch;
}

/**
 * The `fetch` the generated client is built on: credential, deadline, headers, error mapping.
 *
 * Written as a `fetch` replacement rather than as openapi-fetch middleware deliberately. A
 * middleware's `onResponse` can throw, but its `onRequest` cannot compose an `AbortSignal` into
 * the request that is already being issued — so the deadline would have to be established by
 * every caller, which is the one arrangement that guarantees some caller forgets.
 */
export function createTransport(options: TransportOptions): Transport {
  const doFetch = options.fetch ?? globalThis.fetch;
  const defaultClass = options.timeoutClass ?? 'interactive';
  const baseUrl = resolveBaseUrl(options.baseUrl);

  const boundFetch: typeof globalThis.fetch = async (input, init) => {
    /*
      openapi-fetch calls `fetch(new Request(...))` with **no second argument**, and copies any
      init member it does not recognise onto that Request object as a property. So both halves of
      the shape have to be read from the Request, not from `init` — the first draft here read
      `init?.method`, `init?.headers` and `init?.body`, which meant every request from the
      generated client went out as a GET with no headers and no body. It looked right and was
      caught only because a test asserted the header arrived.
    */
    const request = input instanceof Request ? input : new Request(input, init);
    const perRequest = { ...optionsOf(init), ...optionsOf(request) };
    const timeoutMs = perRequest.timeoutMs ?? TIMEOUTS[perRequest.timeoutClass ?? defaultClass];
    const path = pathOf(request.url);

    const headers = new Headers(request.headers);
    headers.set('Authorization', `Bearer ${read(options.token)}`);
    headers.set('User-Agent', options.userAgent);
    if (!headers.has('Accept')) headers.set('Accept', 'application/json');
    if (perRequest.idempotencyKey) headers.set('Idempotency-Key', perRequest.idempotencyKey);
    if (perRequest.ifMatch !== undefined) headers.set('If-Match', String(perRequest.ifMatch));

    const deadline = budget(timeoutMs, perRequest.signal);

    /*
      **The deadline is passed in the init, and nothing downstream may read it off a `Request`.**

      A signal that reaches `fetch` only through a `Request` object is forwarded only as well as
      that object is kept alive, and in at least one shape it is not forwarded at all: measured on
      Node 22.12, `new Request(url, { signal }).signal` never fires its abort event and never
      reports `aborted`, while the same construction with any other init member present does. So
      a deadline handed to a copy-constructed `Request` can simply stop existing, and the request
      hangs for as long as the peer keeps it open — the exact failure the budget exists to
      prevent, arriving through the budget.

      It reads as the option not being applied rather than as the signal being lost, which is why
      the first two attempts at this were aimed at the option. The `hangs` branch of
      `test/stubFetch.ts` meets the same trap from the other side and records it there.

      An explicit init is also the shape any replacement `fetch` — a proxy, a recorder, a test
      stub — finds easiest to read, and it is what the SPA's client sends.
    */
    const carriesBody = request.method !== 'GET' && request.method !== 'HEAD';

    let response: Response;
    try {
      response = await doFetch(request.url, {
        method: request.method,
        headers,
        // The body stays a stream, so an evidence upload is not buffered in this process.
        // Node's fetch requires `duplex` whenever the body is one.
        ...(carriesBody && request.body ? { body: request.body, duplex: 'half' } : {}),
        signal: deadline,
      } as RequestInit);
    } catch (error) {
      // `AbortSignal.timeout()` rejects with a TimeoutError; a caller-driven cancellation is an
      // AbortError. Only the first is a failure worth reporting.
      if (isTimeout(error)) throw new TcmsTimeoutError(request.method, path, timeoutMs);
      throw error;
    }

    if (!response.ok) throw await problemFrom(response, request.method, path);
    return response;
  };

  return { baseUrl, fetch: boundFetch };
}

/** Composes the caller's cancellation with the deadline rather than choosing between them. */
export function budget(ms: number, external?: AbortSignal): AbortSignal {
  const deadline = AbortSignal.timeout(ms);
  return external ? AbortSignal.any([external, deadline]) : deadline;
}

function read(token: TokenSource): string {
  const value = typeof token === 'function' ? token() : token;
  if (!value) {
    throw new TcmsClientError(
      'No API token. Issue one from Settings → API tokens and pass it as TCMS_TOKEN.',
    );
  }
  return value;
}

function isTimeout(error: unknown): boolean {
  return (
    (error instanceof DOMException || error instanceof Error) && error.name === 'TimeoutError'
  );
}

/** The path a message can name, without the origin — which may hold a hostname worth not echoing. */
function pathOf(url: string): string {
  try {
    return new URL(url).pathname;
  } catch {
    return url;
  }
}

/**
 * Reads an RFC-7807 problem document off a refusal.
 *
 * `statusText` is the floor and it is load-bearing: it is empty over HTTP/2 and on any bodiless
 * response, the API's own 401 among them, so without it `detail` becomes `''` and every consumer
 * that falls back to it prints a blank line where the reason should be.
 */
async function problemFrom(response: Response, method: string, path: string): Promise<TcmsApiError> {
  let detail = response.statusText || `The request failed (HTTP ${response.status}).`;
  let title: string | null = null;
  let type: string | null = null;
  let fieldErrors: Record<string, string[]> | null = null;

  try {
    const body: unknown = await response.json();
    if (body && typeof body === 'object') {
      const problem = body as Record<string, unknown>;
      if (typeof problem['detail'] === 'string') detail = problem['detail'];
      else if (typeof problem['title'] === 'string') detail = problem['title'];
      if (typeof problem['title'] === 'string') title = problem['title'];
      if (typeof problem['type'] === 'string') type = problem['type'];
      if (problem['errors'] && typeof problem['errors'] === 'object') {
        fieldErrors = problem['errors'] as Record<string, string[]>;
      }
    }
  } catch {
    /* Not a problem document — a proxy's HTML error page, say. The status text is all we have. */
  }

  return new TcmsApiError({
    status: response.status,
    detail,
    method,
    path,
    title,
    type,
    fieldErrors,
    correlationId: response.headers.get('x-correlation-id'),
    retryAfter: response.headers.get('retry-after'),
  });
}

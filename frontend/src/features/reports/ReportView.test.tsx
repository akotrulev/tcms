import { render, screen, within } from '@testing-library/react'
import { describe, expect, it } from 'vitest'
import { parseReportDocument, type ReportDocument } from '../../lib/reportDocument'
import { ReportView } from './ReportView'

/**
 * The stored model, rendered.
 *
 * This component is presentational and takes a whole document, which is what makes the hostile
 * cases below cheap to write — every one of them is a model a real report could produce and none
 * needs a server. What it asserts:
 *
 *   1. **The provenance block is complete and in the server's order.** §6e makes the header
 *      mandatory and `ReportDocument.headerBlock()` assembles it once *"so three formats cannot
 *      print three different subsets"*. This screen is the fourth renderer of that block, in
 *      another language, with nothing that fails if it silently drops a line — so the labels are
 *      asserted as an **exact ordered list**, which is the only form that catches an omission.
 *   2. **Nothing is recomputed.** The cells rendered are the strings the model carried. A report
 *      view is the single worst place for a second percentage implementation.
 *   3. **An all-zero series draws no bar.** `width: NaN%` renders as a full-width bar in most
 *      browsers — a chart saying everything happened on a report where nothing did. The same
 *      defect `HtmlReportRenderer` fixed once; two renderers, one rule.
 *   4. **A section with no table renders as itself**, not as a broken table — the null is the
 *      server's explicit "this section has no table".
 */

const model = (over: { sections?: unknown[]; metadata?: unknown[] } = {}): ReportDocument =>
  parseReportDocument({
    header: {
      reportType: 'run_summary',
      description: 'A single run: status breakdown, progress per tester, and results by suite.',
      company: 'Northwind Trading',
      projectScope: 'ACME — Acme Platform',
      scopeNote: 'This report covers ACME — Acme Platform in full and no other project.',
      generatedBy: 'Dana Lead',
      generatedAt: '2026-08-04 12:00:00 UTC',
      selection: [{ label: 'runId', value: 'TR-3' }],
    },
    report: {
      title: 'Run summary — TR-3',
      metadata: over.metadata ?? [{ label: 'Pass rate (of recorded)', value: '50.0%' }],
      sections: over.sections ?? [
        {
          heading: 'Results',
          narrative: 'Shares are of the 2 executions recorded in this run.',
          table: {
            columns: ['Status', 'Executions', 'Share'],
            rows: [
              ['PASSED', '1', '50.0%'],
              ['FAILED', '1', '50.0%'],
            ],
          },
          series: [
            {
              name: 'Executions by status',
              points: [
                { label: 'PASSED', value: 1 },
                { label: 'FAILED', value: 1 },
              ],
            },
          ],
        },
      ],
    },
  })

const renderView = (document: ReportDocument) => render(<ReportView document={document} />)

describe('ReportView', () => {
  it('prints the whole provenance block, in the order the server assembles it', () => {
    renderView(model())

    // Through the ROW HEADER role rather than a cell index: the label cell is a `<th scope="row">`,
    // which is what makes each provenance line announce its own label to a screen reader instead of
    // reading as a loose pair of cells.
    const labels = screen
      .getAllByTestId('Report.Header.Row')
      .map((row) => within(row).getByRole('rowheader').textContent)

    expect(labels).toEqual([
      'Report',
      'Report type',
      'Company',
      'Project scope',
      'Scope',
      'Generated by',
      'Generated at',
      'Selection — runId',
      'Pass rate (of recorded)',
    ])
  })

  /*
    The scope note is the line plan §390 requires and the one most likely to be dropped as
    "verbose": without it, two people comparing reports of different scopes compare incomparable
    numbers. Asserted by content rather than position, because its position is already covered above.
  */
  it('renders the scope sentence a reader has to act on', () => {
    renderView(model())

    expect(screen.getByTestId('Report.Header.Grid')).toHaveTextContent(
      /covers ACME — Acme Platform in full and no other project/,
    )
  })

  it('renders the table cells exactly as the model formatted them', () => {
    renderView(model())

    const rows = screen.getAllByTestId('Report.Section.Row')
    expect(rows).toHaveLength(2)
    // "50.0%", not "50%" and not "0.5" — the string the computation produced is the string the
    // export printed, and this screen is not allowed a second opinion about either.
    expect(rows[0]).toHaveTextContent('PASSED')
    expect(rows[0]).toHaveTextContent('50.0%')
    expect(screen.getByTestId('Report.Section.Narrative')).toHaveTextContent(
      'Shares are of the 2 executions recorded in this run.',
    )
  })

  it('scales each bar against the largest value in its own series', () => {
    renderView(
      model({
        sections: [
          {
            heading: 'Executions per tester',
            narrative: null,
            table: null,
            series: [
              {
                name: 'Executions per tester',
                points: [
                  { label: 'Dana', value: 10 },
                  { label: 'Priya', value: 5 },
                ],
              },
            ],
          },
        ],
      }),
    )

    const bars = screen.getAllByTestId('Report.Series.Bar')
    // 100 / 50, never 66.7 / 33.3: a series need not be parts of a whole, so the total is the
    // wrong denominator and drawing against it makes every bar too short.
    expect(bars[0]).toHaveStyle({ width: '100%' })
    expect(bars[1]).toHaveStyle({ width: '50%' })
  })

  it('draws no bar at all for an all-zero series', () => {
    renderView(
      model({
        sections: [
          {
            heading: 'Failures by feature',
            narrative: 'Nothing failed in this run.',
            table: null,
            series: [
              {
                name: 'Failures by feature',
                points: [
                  { label: 'Checkout', value: 0 },
                  { label: 'Payments', value: 0 },
                ],
              },
            ],
          },
        ],
      }),
    )

    // 0%, not NaN% — which most browsers render as a FULL-WIDTH bar, i.e. a chart claiming
    // everything failed on a report saying nothing did.
    for (const bar of screen.getAllByTestId('Report.Series.Bar')) {
      expect(bar).toHaveStyle({ width: '0%' })
    }
  })

  it('renders a narrative-only section without a table', () => {
    renderView(
      model({
        sections: [
          {
            heading: 'Inconsistencies',
            narrative: 'No case both passed and failed within this selection.',
            table: null,
            series: [],
          },
        ],
      }),
    )

    expect(screen.getByTestId('Report.Section.Narrative')).toHaveTextContent(
      'No case both passed and failed within this selection.',
    )
    expect(screen.queryByTestId('Report.Section.Grid')).not.toBeInTheDocument()
  })

  /*
    A report whose selection matched nothing is a legal report, and its header is still the useful
    part. It must not render as a blank page, which is what a failed read looks like — §85's
    404-versus-`200 []` argument, one screen over.
  */
  it('says a report has no sections rather than rendering nothing', () => {
    renderView(model({ sections: [] }))

    expect(screen.getByTestId('Report.NoSections')).toHaveTextContent(/no sections/i)
    expect(screen.getByTestId('Report.Header.Grid')).toBeInTheDocument()
  })
})
